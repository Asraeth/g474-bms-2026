#define BMS_GPIO_BIT(n) (1U << ((n)-1U))
#define BMS_TEMP_GPIO_MASK (BMS_GPIO_BIT(BMS_TEMP1_GPIO)|BMS_GPIO_BIT(BMS_TEMP2_GPIO)|BMS_GPIO_BIT(BMS_TEMP3_GPIO)|BMS_GPIO_BIT(BMS_TEMP4_GPIO)|BMS_GPIO_BIT(BMS_TEMP5_GPIO)|BMS_GPIO_BIT(BMS_TEMP6_GPIO)|BMS_GPIO_BIT(BMS_TEMP7_GPIO)|BMS_GPIO_BIT(BMS_TEMP8_GPIO))
_Static_assert(BMS_TEMP1_GPIO>=1 && BMS_TEMP1_GPIO<=10 && BMS_TEMP2_GPIO>=1 && BMS_TEMP2_GPIO<=10 && BMS_TEMP3_GPIO>=1 && BMS_TEMP3_GPIO<=10 && BMS_TEMP4_GPIO>=1 && BMS_TEMP4_GPIO<=10 && BMS_TEMP5_GPIO>=1 && BMS_TEMP5_GPIO<=10 && BMS_TEMP6_GPIO>=1 && BMS_TEMP6_GPIO<=10 && BMS_TEMP7_GPIO>=1 && BMS_TEMP7_GPIO<=10 && BMS_TEMP8_GPIO>=1 && BMS_TEMP8_GPIO<=10, "Illegal ADBMS temperature GPIO");
_Static_assert(__builtin_popcount(BMS_TEMP_GPIO_MASK)==8, "Duplicate temperature GPIO");
_Static_assert(BMS_PROFILE_LED_RED_GPIO>=1 && BMS_PROFILE_LED_RED_GPIO<=10 && BMS_PROFILE_LED_GREEN_GPIO>=1 && BMS_PROFILE_LED_GREEN_GPIO<=10, "Illegal LED GPIO");
_Static_assert(BMS_PROFILE_LED_RED_GPIO != BMS_PROFILE_LED_GREEN_GPIO, "Duplicate LED GPIO");
_Static_assert((BMS_TEMP_GPIO_MASK & (BMS_GPIO_BIT(BMS_PROFILE_LED_RED_GPIO)|BMS_GPIO_BIT(BMS_PROFILE_LED_GREEN_GPIO)))==0, "LED overwrites analogue temperature input");
